import { readdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const exhibitsRoot = path.join(root, "src/features/living-museum/exhibits");
const output = path.join(root, "src/features/living-museum/registry/generated.ts");
const check = process.argv.includes("--check");
const allowed = new Set(["call-of-duty", "halo", "obsidian-vault", "pokemon-cards", "pokemon-game", "star-wars-game"]);
const entries = existsSync(exhibitsRoot) ? (await readdir(exhibitsRoot, { withFileTypes: true })).filter((item) => item.isDirectory()).map((item) => item.name).sort() : [];
for (const slug of entries) {
  if (!allowed.has(slug)) throw new Error(`Exhibit directory is not allowlisted: ${slug}`);
  for (const file of ["manifest.ts", "ExhibitScene.tsx"]) if (!existsSync(path.join(exhibitsRoot, slug, file))) throw new Error(`Exhibit ${slug} is missing ${file}`);
}
const imports = entries.flatMap((slug, index) => [
  `import { manifest as manifest${index} } from "../exhibits/${slug}/manifest";`,
  `import { ExhibitScene as Scene${index} } from "../exhibits/${slug}/ExhibitScene";`,
]).join("\n");
const modules = entries.map((_, index) => `  { manifest: validateMuseumExhibitV1(manifest${index}), Scene: Scene${index} },`).join("\n");
const source = `// Generated by scripts/generate-museum-registry.mjs. Do not edit.\nimport type { ComponentType } from "react";\nimport type { MuseumExhibitV1 } from "../core/MuseumExhibitV1";\n${entries.length ? `import { validateMuseumExhibitV1 } from "../core/MuseumExhibitV1";\n` : ""}${imports ? `${imports}\n` : ""}\nexport type MuseumExhibitModule = {\n  manifest: MuseumExhibitV1;\n  Scene: ComponentType<{ active: boolean; reducedMotion: boolean }>;\n};\n\nexport const museumExhibits: readonly MuseumExhibitModule[] = [\n${modules}\n];\n`;
if (check) {
  const current = await readFile(output, "utf8");
  if (current !== source) { console.error("Museum registry is stale. Run npm run museum:registry."); process.exit(1); }
} else {
  await writeFile(output, source);
  console.log(`Generated ${path.relative(root, output)} with ${entries.length} exhibits.`);
}
