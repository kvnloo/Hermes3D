import { chromium } from "playwright";
import fs from "node:fs/promises";
import path from "node:path";

const baseUrl = process.env.BASE_URL ?? "http://127.0.0.1:43891";
const output = path.resolve("docs/mobile-agent-game/evidence");
const videoDir = path.join(output, "video-tmp");
await fs.mkdir(videoDir, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: "/opt/google/chrome/chrome", args: ["--disable-dev-shm-usage"] });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, recordVideo: { dir: videoDir, size: { width: 390, height: 844 } } });
const page = await context.newPage();
await page.goto(`${baseUrl}/office/game`, { waitUntil: "networkidle" });
await page.locator("canvas").waitFor({ state: "visible" });
await page.waitForTimeout(3_000);
await page.getByRole("button", { name: "Build" }).click();
await page.waitForTimeout(3_000);
await page.getByRole("button", { name: "Assign Atlas locally" }).click();
await page.waitForTimeout(4_000);
await page.getByRole("button", { name: "Attach review evidence" }).click();
await page.waitForTimeout(4_000);
await page.getByRole("button", { name: "Agents" }).click();
await page.waitForTimeout(3_000);
await page.goBack();
await page.waitForTimeout(3_000);
await page.getByRole("button", { name: "Use list view" }).click();
await page.waitForTimeout(4_000);
await page.getByRole("button", { name: /Dim0 company/ }).click();
await page.waitForTimeout(3_000);
await page.screenshot({ path: path.join(output, "walkthrough-final-390x844.png") });
const rawVideo = await page.video().path();
await context.close();
await fs.copyFile(rawVideo, path.join(output, "walkthrough-390x844.webm"));
await fs.rm(videoDir, { recursive: true, force: true });
await browser.close();
console.log("docs/mobile-agent-game/evidence/walkthrough-390x844.webm");
